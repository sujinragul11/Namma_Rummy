const assert = require('node:assert/strict');
const Engine = require('../src/game/GameEngine');
const game = new Engine('wrong-declaration-test', 'close_joker', 3);
for (const id of ['a', 'b', 'c']) game.addPlayer(id, id);
const offender = game.currentPlayer;
const { card } = game.drawCard(offender);
assert.equal(game.declare(offender, card.id, []).valid, false);
assert.equal(game.players.get(offender).hand.length, 13);
assert.equal(game.players.get(offender).wrongDeclaration, true);
const restored = Engine.fromJSON(JSON.parse(JSON.stringify(game.serialize())));
const voluntary = restored.currentPlayer;
const result = restored.drop(voluntary);
const wrong = result.players.find(p => p.id === offender);
assert.equal(wrong.outcome, 'wrong_declaration');
assert.equal(wrong.points, 80);
assert.equal(wrong.melds.flatMap(m => m.cards).length, 13);
assert.equal(result.players.find(p => p.id === voluntary).outcome, 'dropped');
restored.startNextRound();
assert.equal(restored.players.get(offender).wrongDeclaration, false);
console.log('PASS: wrong declaration reason, 80 points, full 13-card result, restart, normal drops and next-round reset');

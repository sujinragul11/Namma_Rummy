const assert = require('node:assert/strict');
const Engine = require('../src/game/GameEngine');
const game = new Engine('score-test', 'pool', 2);
game.addPlayer('a', 'Alice');
game.addPlayer('b', 'Bob');
game.drop(game.currentPlayer);
assert.equal(game.scoreHistory.length, 1);
assert.equal(game.scoreHistory[0].players.length, 2);
assert.ok(game.scoreHistory[0].players.every(p => !p.hand && !p.melds));
const restored = Engine.fromJSON(JSON.parse(JSON.stringify(game.serialize())));
assert.deepEqual(restored.scoreHistory, game.scoreHistory);
restored.startNextRound();
assert.equal(restored.getGameState('a').scoreHistory.length, 1);
restored.drop(restored.currentPlayer);
assert.equal(restored.scoreHistory.length, 2);
const old = game.serialize();
delete old.scoreHistory;
assert.deepEqual(Engine.fromJSON(old).scoreHistory, []);
const deals = new Engine('deals-test', 'deals_2', 2);
deals.addPlayer('a', 'Alice');
deals.addPlayer('b', 'Bob');
deals.drop(deals.currentPlayer);
assert.ok(deals.scoreHistory[0].players.every(p => Number.isInteger(p.chips)));
console.log('PASS: round scores, next round, restart, legacy snapshots, deals chips and no hidden cards');
